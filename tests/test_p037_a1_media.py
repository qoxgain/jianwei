def test_two_io_workers_finish_stream_and_multiple_waiters(tmp_path):
 async def run():
  limiter=anyio.to_thread.current_default_thread_limiter();old=limiter.total_tokens;limiter.total_tokens=2
  gate=file_gate(tmp_path/'gate',wait_timeout=.5,poll_seconds=.002);first=anyio.Event();resume=anyio.Event();done=[]
  async def call(name):
   async def send(m):
    if name=='owner' and m['type']=='http.response.body' and not first.is_set():first.set();await resume.wait()
   async def receive():await anyio.sleep_forever()
   await GuardedResponse(StreamingResponse(iter([b'first',b'next'])),gate,lambda:None)({'type':'http','method':'GET','asgi':{'spec_version':'2.4'}},receive,send)
   done.append(name)
  try:
   with anyio.fail_after(2):
    async with anyio.create_task_group() as tg:
     tg.start_soon(call,'owner');await first.wait()
     for i in range(6):tg.start_soon(call,str(i))
     await anyio.sleep(.05)
     assert limiter.borrowed_tokens==0
     resume.set()
   assert len(done)==7
  finally:limiter.total_tokens=old
 anyio.run(run)


def test_wait_timeout_and_cancel_do_not_take_pool_tokens_or_leak_lock(tmp_path):
 async def run():
  gate=file_gate(tmp_path/'gate',wait_timeout=.05,poll_seconds=.002);waiting=anyio.Event();cancelled=anyio.Event()
  # Independent descriptor, not a borrowed context, represents another request.
  fd=gate.try_acquire_raw();assert fd is not None
  try:
   with pytest.raises(ContractError) as e:
    async with gate.async_hold():pytest.fail('lease entered despite other owner')
   assert e.value.code=='RESOURCE_LOCK_TIMEOUT'
   async def waiter():
    with anyio.CancelScope() as scope:
     scopes.append(scope);waiting.set()
     async with gate.async_hold(timeout=1):pytest.fail('cancelled waiter acquired lease')
    cancelled.set()
   scopes=[]
   async with anyio.create_task_group() as tg:
    tg.start_soon(waiter);await waiting.wait();scopes[0].cancel();await cancelled.wait()
   assert anyio.to_thread.current_default_thread_limiter().borrowed_tokens==0
  finally:gate.release_raw(fd)
  async with gate.async_hold():pass
 anyio.run(run)


def test_cancelled_and_exceptional_file_send_release_file_and_lease(tmp_path):
 async def run():
  file=tmp_path/'fixture.bin';file.write_bytes(b'generated bytes'*1000);gate=file_gate(tmp_path/'gate',wait_timeout=.1)
  first=anyio.Event();scopes=[]
  async def receive():await anyio.sleep_forever()
  async def send(m):
   if m['type']=='http.response.body':first.set();await anyio.sleep_forever()
  async def owner():
   with anyio.CancelScope() as scope:
    scopes.append(scope)
    await GuardedResponse(FileResponse(file),gate,lambda:None)({'type':'http','method':'GET','headers':[]},receive,send)
  async with anyio.create_task_group() as tg:
   tg.start_soon(owner);await first.wait();scopes[0].cancel()
  fd=gate.try_acquire_raw();assert fd is not None;gate.release_raw(fd)
  assert not [p for p in Path('/proc/self/fd').iterdir() if p.is_symlink() and os.readlink(p)==str(file)]
  async def broken(m):raise RuntimeError('generated response transport failure')
  with pytest.raises(RuntimeError):
   await GuardedResponse(FileResponse(file),gate,lambda:None)({'type':'http','method':'GET','headers':[]},receive,broken)
  async with gate.async_hold():pass
 anyio.run(run)


