def asset():return {'asset_id':'generated-fixture','kind':'video','path':'unused.mp4','sha256':'a'*64,'provenance':{'split':'unassigned','capture_session_id':None,'camera_id':None,'view_id':None,'captured_at':None}}


def test_source_guard_rejects_before_probe_or_preview(monkeypatch,tmp_path):
    monkeypatch.setattr(source_audit,'PROJECT_ROOT',tmp_path);monkeypatch.setattr(source_audit,'admitted_bundle',lambda *args:None)
    def deny(*args):raise ContractError('MOTION_SEALED_FORBIDDEN','unit generated sealed-source fixture')
    def forbidden(*args):raise AssertionError('Content accessed after denial')
    monkeypatch.setattr(source_audit,'admission',deny);monkeypatch.setattr(source_audit,'probe_video',forbidden);monkeypatch.setattr(source_audit,'screen',forbidden)
    r=source_audit.audit({'assets':[asset()]},None,tmp_path/'artifacts/audit',True)
    assert r['blocked_or_failed']==1 and r['development_bytes_verified']==0 and r['verified_independent_pairs']==0
    assert r['sources_missing_capture_metadata']==1


def test_byte_identity_and_container_hints_do_not_approve_capture_independence(monkeypatch,tmp_path):
    monkeypatch.setattr(source_audit,'PROJECT_ROOT',tmp_path);monkeypatch.setattr(source_audit,'admitted_bundle',lambda *args:None)
    video=tmp_path/'generated.bin';video.write_bytes(b'generated bytes only')
    monkeypatch.setattr(source_audit,'admission',lambda *args:video);monkeypatch.setattr(source_audit,'probe_video',lambda *args:{'duration_seconds':120})
    a=asset();a['media']={'creation_time_hint':'2025-01-01T10:00:00Z'}
    r=source_audit.audit({'assets':[a]},None,tmp_path/'artifacts/audit')
    private=json.loads((tmp_path/'artifacts/audit/sources-private.json').read_text())['records'][0]
    assert r['development_bytes_verified']==1 and r['verified_independent_pairs']==0 and private['independent_transfer_allowed'] is False
    assert private['metadata_creation_hint_is_capture_truth'] is False and private['near_duplicate_review']=='pending'
