"""Generate product JSON Schemas from the shared Python contracts.

Run with ``python -m scripts.export_schemas`` from the checkout root.
The implemented API snapshot is generated by scripts.export_openapi and served
at /openapi.json; schemas here describe the shared configuration/data contracts.
"""
import json
from pathlib import Path

from packages.contracts.models import Forecast, Knowledge, MemoryPatch, SystemConfig, TeacherResult
from packages.contracts.ingestion import ImportRequest
from packages.contracts.sop import RevisionRequest, DecisionRequest, EvidenceRecord
from packages.contracts.temporal import TrainRequest, EvaluationRequest, ReadinessRequest
from packages.contracts.dataset import DatasetManifest
from packages.contracts.scenes import SceneKnowledge
from packages.contracts.configuration import SceneConfig
from packages.contracts.learning import Episode, FeatureSpace, FeatureBatch, ActivityObservation, Prediction, NormativeExpectation, MemorySnapshot, StateSnapshot, EventOccurrence


ROOT = Path(__file__).resolve().parents[1]
MODELS = {
    "sop_revision_request": RevisionRequest,
    "sop_decision_request": DecisionRequest,
    "sop_evidence_record": EvidenceRecord,
    "temporal_readiness_request": ReadinessRequest,
    "dataset_manifest": DatasetManifest,
    "temporal_train_request": TrainRequest,
    "temporal_evaluation_request": EvaluationRequest,
    "import_request": ImportRequest,
    "system": SystemConfig,
    "scene_config": SceneConfig,
    "scene_knowledge": SceneKnowledge,
    "episode": Episode,
    "feature_space": FeatureSpace,
    "feature_batch": FeatureBatch,
    "observation": ActivityObservation,
    "prediction": Prediction,
    "normative_expectation": NormativeExpectation,
    "memory_snapshot": MemorySnapshot,
    "state_snapshot": StateSnapshot,
    "event_occurrence": EventOccurrence,
    "labels": Knowledge,
    "memory_patch": MemoryPatch,
    "teacher_result": TeacherResult,
    "forecast": Forecast,
}


def schemas():
    return {
        name: {**model.model_json_schema(), "$schema": "https://json-schema.org/draft/2020-12/schema"}
        for name, model in MODELS.items()
    }


def main():
    directory = ROOT / "schemas"
    directory.mkdir(exist_ok=True)
    for name, schema in schemas().items():
        (directory / f"{name}.schema.json").write_text(
            json.dumps(schema, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
    print(f"Generated {len(MODELS)} product JSON Schemas")


if __name__ == "__main__":
    main()
